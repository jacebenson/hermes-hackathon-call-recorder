// No installs. Point HERMES_DESKTOP at an existing SDK workspace with esbuild.
import { copyFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
const desktop = process.env.HERMES_DESKTOP || '/home/jace/.hermes/hermes-agent/.build/webapp-workspace/apps/desktop'
const { build } = createRequire(`${desktop}/package.json`)('esbuild')
await build({ entryPoints: [fileURLToPath(new URL('../desktop/src/plugin.mjs', import.meta.url))], outfile: fileURLToPath(new URL('../desktop/plugin.js', import.meta.url)), bundle: true, format: 'esm', external: ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime'], banner: { js: '// Generated by scripts/build-desktop.mjs; edit desktop/src, not this file.' } })

const dist = fileURLToPath(new URL('../packages/call-recorder/', import.meta.url))
mkdirSync(`${dist}/desktop`, { recursive: true })
copyFileSync(fileURLToPath(new URL('../desktop/plugin.js', import.meta.url)), `${dist}/desktop/plugin.js`)
